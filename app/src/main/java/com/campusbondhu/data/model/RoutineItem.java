package com.campusbondhu.data.model;

public class RoutineItem {
    private String routineId;
    private String courseCode;
    private String room;
    private String day;
    private String time;

    public RoutineItem() {}

    public String getRoutineId() { return routineId; }
    public void setRoutineId(String v) { routineId = v; }
    public String getCourseCode() { return courseCode; }
    public void setCourseCode(String v) { courseCode = v; }
    public String getRoom() { return room; }
    public void setRoom(String v) { room = v; }
    public String getDay() { return day; }
    public void setDay(String v) { day = v; }
    public String getTime() { return time; }
    public void setTime(String v) { time = v; }
}
